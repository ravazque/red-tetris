const toShadow = (rows: readonly string[]) =>
  rows
    .flatMap((row, y) => [...row].flatMap((pixel, x) => (pixel === '#' ? [`${x + 1}em ${y + 1}em currentColor`] : [])))
    .join(', ');

const SHAPES = new Map(Object.entries(GLYPHS).map(([char, rows]) => [char, toShadow(rows)]));

export const glyphShape = (char: string) => SHAPES.get(char.toUpperCase()) ?? 'none';
